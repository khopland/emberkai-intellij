"""Add red-green vision deficiency colors to the Emberkai editor schemes.

IntelliJ reads a `deuteranopia` or `protanopia` attribute instead of `value` when
Settings > Appearance & Behavior > Appearance > Accessibility > "Adjust colors for red-green
vision deficiency" is on. Emberkai's added, modified, and deleted colors are green, cyan, and
rose, and green against rose looks alike to most red-green colorblind people. With the option
on, added becomes the scheme's cyan, modified its violet, and deleted stays rose; diff and
coverage backgrounds use stronger tints so they also stay apart.

The script is idempotent: it removes existing alternates before adding them again. Run it
after changing a scheme's VCS, diff, or coverage colors:

    python3 scripts/colorblind_alternates.py src/main/resources/schemes/*.xml

Light Contrast is skipped: light_contrast.py darkens Light's alternates with the colors they replace.
"""
import re
import sys
from pathlib import Path

ALTERNATE = re.compile(r' (?:deuteranopia|protanopia)="[^"]*"')

# Tint strengths found by maximizing the smallest simulated distance between inserted,
# modified, and deleted diff backgrounds while text on them stays at 4.5:1 (dark) or 7:1 (light).
TINTS = {"dark": (0.35, 0.32), "light": (0.35, 0.23)}
LINE_TINT = 0.1  # DIFF_* FOREGROUND: the lighter fill of whitespace-only changes.


def rgb(value):
    value = value.lstrip("#")
    return [int(value[i:i + 2], 16) for i in (0, 2, 4)]


def blend(color, background, alpha):
    fg, bg = rgb(color), rgb(background)
    return "#" + "".join("%02x" % round(b + (f - b) * alpha) for f, b in zip(fg, bg))


def tint_alpha(tint, color, background):
    """How strongly `color` was mixed into `background` to give `tint`."""
    t, f, b = rgb(tint), rgb(color), rgb(background)
    weights = [abs(fc - bc) for fc, bc in zip(f, b)]
    channel = weights.index(max(weights))
    return (t[channel] - b[channel]) / (f[channel] - b[channel])


def color_option(text, name):
    match = re.search(r'<option name="%s" value="(#?[0-9a-fA-F]{6})"' % re.escape(name), text)
    assert match, name
    return "#" + match.group(1).lstrip("#").lower()


def attribute_field(text, name, field):
    block = re.search(r'<option name="%s">(.*?)</option>\s*\n    <option' % re.escape(name), text, re.S)
    assert block, name
    match = re.search(r'<option name="%s" value="(#?[0-9a-fA-F]{6})"' % field, block.group(1))
    assert match, (name, field)
    return "#" + match.group(1).lstrip("#").lower()


def add_alternate(text, pattern, alternate):
    """Give the single `value="..."` option matched by `pattern` an alternate color."""
    matches = list(re.finditer(pattern, text, re.S))
    assert len(matches) == 1, pattern
    match = matches[0]
    insert = match.end()
    return text[:insert] + ' deuteranopia="%s" protanopia="%s"' % (alternate, alternate) + text[insert:]


def process(path):
    if "light-contrast" in path.name:
        print("%s: skipped, generated by light_contrast.py" % path.name)
        return
    text = ALTERNATE.sub("", path.read_text())
    background = attribute_field(text, "TEXT", "BACKGROUND")
    family = "light" if sum(rgb(background)) > 382 else "dark"
    green = color_option(text, "ADDED_LINES_COLOR")
    cyan = color_option(text, "FILESTATUS_MODIFIED")
    violet = color_option(text, "FILESTATUS_MERGED")
    inserted_tint, modified_tint = TINTS[family]

    colors_end = text.index("</colors>")
    colors, rest = text[:colors_end], text[colors_end:]
    for name, value in re.findall(r'<option name="([^"]+)" value="(#?[0-9a-fA-F]{6})"', colors):
        value = "#" + value.lstrip("#").lower()
        added = name in ("ADDED_LINES_COLOR", "IGNORED_ADDED_LINES_BORDER_COLOR") or (name.startswith("FILESTATUS_") and value == green)
        modified = name in ("MODIFIED_LINES_COLOR", "IGNORED_MODIFIED_LINES_BORDER_COLOR") or (name.startswith("FILESTATUS_") and value == cyan)
        if added or modified:
            colors = add_alternate(colors, r'<option name="%s" value="[^"]+"' % re.escape(name), cyan if added else violet)
    text = colors + rest

    def field(name, option, alternate):
        nonlocal text
        text = add_alternate(text, r'<option name="%s">\s*<value>(?:(?!</value>).)*?<option name="%s" value="[^"]+"' % (re.escape(name), option), alternate)

    field("DIFF_INSERTED", "BACKGROUND", blend(cyan, background, inserted_tint))
    field("DIFF_INSERTED", "FOREGROUND", blend(cyan, background, LINE_TINT))
    field("DIFF_INSERTED", "ERROR_STRIPE_COLOR", cyan)
    field("DIFF_MODIFIED", "BACKGROUND", blend(violet, background, modified_tint))
    field("DIFF_MODIFIED", "FOREGROUND", blend(violet, background, LINE_TINT))
    field("DIFF_MODIFIED", "ERROR_STRIPE_COLOR", violet)
    covered = attribute_field(text, "LINE_FULL_COVERAGE", "BACKGROUND")
    field("LINE_FULL_COVERAGE", "BACKGROUND", blend(cyan, background, tint_alpha(covered, green, background)))
    path.write_text(text)
    print("%s: added %s, modified %s" % (path.name, cyan, violet))


for argument in sys.argv[1:]:
    process(Path(argument))
